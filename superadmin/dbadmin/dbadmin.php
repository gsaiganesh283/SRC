function toggleDropdown(id) {
    var dropdown = document.getElementById(id);
    var allDropdowns = document.querySelectorAll('[id$="Dropdown"]');
    allDropdowns.forEach(function(d) {
        if (d.id !== id) d.style.display = 'none';
    });
    dropdown.style.display = dropdown.style.display === 'none' ? 'block' : 'none';
}
// Close dropdowns when clicking outside
document.addEventListener('click', function(e) {
    if (!e.target.matches('.dbadmin-export-btn')) {
        var dropdowns = document.querySelectorAll('[id$="Dropdown"]');
        dropdowns.forEach(function(d) { d.style.display = 'none'; });
    }
});

// Update time every second
function updateDateTime() {
    const now = new Date();
    
    // Update time
    const hours = now.getHours();
    const minutes = now.getMinutes();
    const seconds = now.getSeconds();
    const ampm = hours >= 12 ? 'PM' : 'AM';
    const displayHours = hours % 12 || 12;
    const timeString = String(displayHours).padStart(2, '0') + ':' + 
                       String(minutes).padStart(2, '0') + ':' + 
                       String(seconds).padStart(2, '0') + ' ' + ampm;
    document.getElementById('currentTime').textContent = timeString;
    
    // Update date
    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    const dateString = String(now.getDate()).padStart(2, '0') + ' ' + 
                      months[now.getMonth()] + ' ' + 
                      now.getFullYear();
    document.getElementById('currentDate').textContent = dateString;
    
    // Update day
    const days = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
    document.getElementById('currentDay').textContent = days[now.getDay()];
}

// Update immediately and then every second
updateDateTime();
setInterval(updateDateTime, 1000);
